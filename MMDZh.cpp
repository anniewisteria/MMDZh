// SJIS 字节 → 日文 W（宽松：GBK 往返保留下来的字节在 932 下尽量还原）。
// 解不出或含字面 '?' 则失败，调用方保留改写前的 W 文本。
static bool Decode932Lenient(const char* p, int n, std::wstring& out)
{
    if (!p || n <= 0) return false;
    int wl = MultiByteToWideChar(932, 0, p, n, nullptr, 0);
    if (wl <= 0) return false;
    out.resize(wl);
    if (MultiByteToWideChar(932, 0, p, n, &out[0], wl) != wl) return false;
    return !out.empty() && out.find(L'?') == std::wstring::npos;
}

