// 把 MMD 的 ANSI 字符串解码并翻译。
//
// 字节有两种来源（实测日志确认）：
//   ① MMD 自带静态 SJIS 文本（面板日文、About 作者名）→ 按 932 解；
//   ② 自绘控件经 GetWindowTextA 在中文系统上取回的字节 → 按 GBK(936) 解
//      （蓝按钮的 パース、我们写入的 透视 都走这条）。
// 两种字节可能都能“解码成功”，用词典命中、全角假名归属、我们写入值集合
// 来决定该信哪个码页；判定不了（纯汉字）一律信 932（MMD 本体是日文软件）。
struct ResolvedText {
    const wchar_t* text;     // nullptr 表示调用方应走原 A 函数
    int            len;      // 传给 W 版 API 的字符数（显式，不含 NUL）
    const wchar_t* tag;
    bool           chinese;  // 输出中文，需要中文字形
};

static thread_local std::wstring tls932;
static thread_local std::wstring tls936;
static thread_local std::wstring tlsPat;

// 平假名/全角片假名（注意 U+30FB「・」是中点，不算假名）
static int CountFullKana(const std::wstring& s)
{
    int n = 0;
    for (wchar_t c : s)
        if ((c >= 0x3041 && c <= 0x3096) || (c >= 0x30A1 && c <= 0x30FA))
            ++n;
    return n;
}

// 半角片假名（U+FF61-FF9F）。SJIS 静态文本大量使用（ｶﾒﾗ･照明･ｱｸｾｻﾘ、
// ﾌﾚ･ｽﾄｯﾌﾟ）；而 GBK 解码正常中文不会落到该区段，因此它是 932 侧的
// 强信号。注意 932 解 GBK 字节时也可能产生少量半角噪声（パース→･ﾑｩ），
// 不能见一个就改判，需与对侧全角假名数量比较（见 ResolveA 第 3 步）。
static int CountHalfKana932(const std::wstring& s)
{
    int n = 0;
    for (wchar_t c : s)
        if (c >= 0xFF61 && c <= 0xFF9F)
            ++n;
    return n;
}

// 我们写入控件的全部中文值（GDI 层遇到这些 GBK 字节时必须按中文渲染）
// （定义前置到词典区，供 DllMain 早期建表）

static int CountA(LPCSTR s, int cch)
{
    int n = 0;
    for (const unsigned char* p = (const unsigned char*)s; ; ++p, ++n) {
        if (cch >= 0 && n >= cch) break;
        if (*p == 0) break;
    }
    return n;
}

static bool StrictDecode(int cp, LPCSTR s, int n, std::wstring& out)
{
    int wlen = MultiByteToWideChar(cp, MB_ERR_INVALID_CHARS, s, n, nullptr, 0);
    if (wlen <= 0) return false;
    out.resize(wlen);
    return MultiByteToWideChar(cp, MB_ERR_INVALID_CHARS, s, n, &out[0], wlen) > 0;
}

static ResolvedText ResolveA(LPCSTR s, int cch)
{
    if (!s) return { nullptr, 0, L"NULL", false };
    // 汉化已关闭：GDI 文字与 MessageBox 全部走原 A 函数（MMD 日文原貌）
    if (!IsZhOn()) return { nullptr, 0, L"OFF", false };

    int n = CountA(s, cch);
    bool hasHigh = false;
    for (int i = 0; i < n; ++i)
        if ((unsigned char)s[i] >= 0x80) { hasHigh = true; break; }
    if (n == 0 || !hasHigh) return { nullptr, 0, L"ASCII", false };

    bool ok932 = StrictDecode(932, s, n, tls932);
    bool ok936 = StrictDecode(936, s, n, tls936);
    if (!ok932 && !ok936) return { nullptr, 0, L"INVALID", false };

    // —— 0. 创建期即被 GBK 打成字面 '?' 的本影模式按钮（???ﾓｰﾄﾞ1/2）——
    static const wchar_t kBenYing[] = L"本影";
    if (ok932 && DamagedSelfShadowCaption(tls932))
        return { kBenYing, 2, L"DMG932", true };
    if (ok936 && DamagedSelfShadowCaption(tls936))
        return { kBenYing, 2, L"DMG936", true };

    // —— 1. 词典优先：GBK 解码先于 932（控件自绘的日文/中文标签都在 936 侧）——
    if (ok936) {
        if (auto* zh = DictLookup(tls936))
            return { zh->c_str(), (int)zh->size(), L"DICT936", true };
        if (g_zhValues.find(tls936) != g_zhValues.end())
            return { tls936.c_str(), (int)tls936.size(), L"OURS936", true };
    }
    if (ok932) {
        if (auto* zh = DictLookup(tls932))
            return { zh->c_str(), (int)zh->size(), L"DICT932", true };
    }

    // —— 1b. 含动态模型名的弹窗正文模板（932 原形 / 936 GBK 打散两侧都试）——
    if (ok932 && PatternLookupJp(tls932, tlsPat))
        return { tlsPat.c_str(), (int)tlsPat.size(), L"PAT932", true };
    // —— 1c. MME 固定日文前缀 + 动态明细的报错框 ——
    if (ok932 && PrefixLookupJp(tls932, tlsPat))
        return { tlsPat.c_str(), (int)tlsPat.size(), L"PRE932", true };
    // —— 1d. MME 日文句夹在路径/明细中间（路径在前）的报错框 ——
    if (ok932 && SubstrReplaceJp(tls932, tlsPat))
        return { tlsPat.c_str(), (int)tlsPat.size(), L"SUB932", true };
    if (ok936 &&
        (PatternLookupJp(tls936, tlsPat) ||
         PatternLookupMojibake(tls936, tlsPat)))
        return { tlsPat.c_str(), (int)tlsPat.size(), L"PAT936", true };

    // —— 2. About 作者名（混排串，按 932 解）——
    if (ok932 &&
        (tls932.find(L"programmed by") != std::wstring::npos ||
         tls932.find(L"Programmed by") != std::wstring::npos))
        return { tls932.c_str(), (int)tls932.size(), L"ABOUT", false };

    const int fk932 = ok932 ? CountFullKana(tls932) : 0;
    const int hk932 = ok932 ? CountHalfKana932(tls932) : 0;
    const int fk936 = ok936 ? CountFullKana(tls936) : 0;

    // —— 3. 假名归属 ——
    // 全角假名只在一侧出现时，通常归那侧（パース 与 ･ﾑｩ 的分水岭）；
    // 但 932 侧若有【更多】半角片假名（ｶﾒﾗ･照明･ｱｸｾｻﾘ 实测 8:1 压过
    // GBK 侧碰巧解出的单个「ケ」），判为 SJIS 静态文本；パース 是
    // 3:3 平局，仍归 936（自绘控件路径）。
    if (fk936 > 0 && fk932 == 0) {
        if (ok932 && hk932 > fk936)
            return { tls932.c_str(), (int)tls932.size(), L"JP932H", false };
        return { tls936.c_str(), (int)tls936.size(), L"JP936", false };
    }
    if (fk932 > 0)
        return { tls932.c_str(), (int)tls932.size(), L"JP932", false };

    // —— 4. 只有一侧解得出 ——
    if (!ok932 && ok936)
        return { tls936.c_str(), (int)tls936.size(), L"JP936", false };
    if (ok932 && !ok936)
        return { tls932.c_str(), (int)tls932.size(), L"JP932", false };

    // —— 5. 两侧都合法、都无全角假名（樋口優 vs 旙岥桪）：信 932 ——
    return { tls932.c_str(), (int)tls932.size(), L"JP932", false };
}

