// 对一段控件 W 文本决定汉化结果。
//   1) 词典命中 → 中文；
//   2) 本插件写入过的文本 → 不动；
//   3) 其余疑似 SJIS 被 GBK 打坏的文本：取 A 字节严格 932 恢复（全角假名
//      或词典白名单才接受），恢复后再查词典。
// 「本影」模式按钮：原文 ｾﾙﾌ影ﾓｰﾄﾞ1/2（或全角 セルフ影モード1/2）在
// CreateWindowExA 瞬间被系统码页 GBK 转换，ｾﾙﾌ影 直接变成字面 '?'，
// 事后无法还原。检测「≥2 个 '?' + モード/ﾓｰ 片段」这一唯一特征，
// 统一改成「本影」（控件层、GDI 自绘层共用）。
static bool DamagedSelfShadowCaption(const std::wstring& w)
{
    int q = 0;
    for (wchar_t c : w) if (c == L'?') ++q;
    if (q < 2) return false;
    return w.find(L"モード") != std::wstring::npos ||
           w.find(L"ﾓｰ")   != std::wstring::npos;
}

// rawA/rawLen 由调用方用 A 版消息取得；为空则不尝试恢复。
static bool ResolveControlText(const std::wstring& cur,
                               const char* rawA, int rawLen,
                               std::wstring& nt)
{
    nt.clear();
    if (cur.empty()) return false;

    // GBK 污染形态（词典预演对照）：直接得到原文，再按开关给中文
    if (const std::wstring* jp = MojibakeLookup(cur)) {
        if (const std::wstring* z = DictLookup(*jp)) nt = *z;
        else nt = *jp;
        return nt != cur;
    }
    if (auto* z = DictLookup(cur)) { nt = *z; return nt != cur; }
    // 动态正文：优先按乱码形态匹配（覆盖 SetWindowTextA 打坏的静态控件）
    if (PatternLookupMojibake(cur, nt)) return true;
    if (PatternLookupJp(cur, nt)) return true;
    if (IsOurs(cur)) return false;

    std::wstring rec;
    if (rawA && rawLen > 0 && RecoverStrict932(rawA, rawLen, rec) &&
        rec != cur && RecoveryLooksJapanese(rec)) {
        if (auto* z = DictLookup(rec)) nt = *z;
        else if (!PatternLookupJp(rec, nt) && !PrefixLookupJp(rec, nt)
                 && !SubstrReplaceJp(rec, nt)) nt = rec;
        return true;
    }
    return false;
}

// MMD 9.32x64 是 Unicode 程序：按钮/静态控件多为 Unicode 窗口，日文 caption
// （半角假名 ﾍﾟｰｽﾄ / ｾﾙﾌ影 / ｾｯﾄ 等）以 W 文本存储，原生显示完全正常。
// 但用 GetWindowTextA 反取时系统固定按 GBK 转换，半角假名在 GBK 无对应，
// 全部变成字面 '?'（不可逆）。旧版把这份 0x3F 字节当「原文快照」保存，
// 关闭汉化时再写回，日文就永久变问号（只能重启）。
// 这些是 MMD 9.32x64 对话框里位置固定的控件 ID，问号已形成后据此救回原文。
struct DamagedFix { int id; const wchar_t* jp; const wchar_t* zh; };
static const DamagedFix kDamagedFixes[] = {
    { 421, L"ﾍﾟｰｽﾄ",      L"粘贴"   },  // 帧操作：貼り付け
    { 498, L"反転ﾍﾟｰｽﾄ",   L"反转粘贴" },
    { 440, L"ｾﾙﾌ影",        L"本影"  },  // 本影操作：模式按钮未点亮态
    { 555, L"ｾｯﾄ",          L"设置"   },  // 右上角工具条
};
static bool LooksQuestionDestroyed(const std::wstring& w)
{
    if (w.empty() || w.size() > 12) return false;
    int q = 0;
    for (wchar_t c : w) if (c == L'?') ++q;
    if (q <= 0) return false;
    return q * 2 >= (int)w.size();   // '?' 占一半以上才算损坏
}
static const DamagedFix* SalvageByCtrlId(HWND h, const std::wstring& cur)
{
    if (!LooksQuestionDestroyed(cur)) return nullptr;
    const int id = GetDlgCtrlID(h);
    for (const auto& f : kDamagedFixes)
        if (f.id == id) return &f;
    return nullptr;
}

// 普通按钮/静态文本：确定 MMD 原文 orig（W）与应显示的中文 zh。
// 成功返回 true（zh 为空表示无需改写）。
static bool ResolvePlainControl(HWND hCtrl, const std::wstring& cur,
                                const char* rawA, int rawLen,
                                std::wstring& orig, std::wstring& zh)
{
    orig.clear();
    zh.clear();
    if (cur.empty() || IsOurs(cur)) return false;

    // 1) 半角假名已被 GBK 打成问号：本影点亮态旧特判 + 固定控件 ID 救回
    if (DamagedSelfShadowCaption(cur)) {
        orig = L"ｾﾙﾌ影ﾓｰﾄﾞ1";
        zh   = L"本影";
        return true;
    }
    if (const DamagedFix* fx = SalvageByCtrlId(hCtrl, cur)) {
        orig = fx->jp;
        zh   = fx->zh;
        return true;
    }

    // 2) cur 本身就是正常日文（Unicode 程序的常态）
    if (const std::wstring* z = DictLookup(cur)) {
        orig = cur;
        zh   = *z;
        return zh != cur;
    }

    // 3) GBK 污染形态：词典预演对照确定原文
    if (const std::wstring* jp = MojibakeLookup(cur)) {
        orig = *jp;
        if (const std::wstring* z = DictLookup(orig)) zh = *z;
        return true;
    }

    // 4) 其余动态模板 / 严格 932 恢复，沿用完整解析
    std::wstring nt;
    if (ResolveControlText(cur, rawA, rawLen, nt)) {
        zh = nt;
        if (rawA && rawLen > 0) {
            std::wstring rec;
            if (RecoverStrict932(rawA, rawLen, rec) &&
                RecoveryLooksJapanese(rec))
                orig = rec;
        }
        if (orig.empty()) orig = cur;
        return true;
    }
    return false;
}

// 普通控件原文留底：Unicode 窗存 W 原文（关闭时 SendMessageW 原样还原，
// 绝不经过 GBK）；ANSI 窗存 SJIS 字节（关闭时 SetWindowTextA 还原）。
static void SavePlainSnapshot(HWND hCtrl, const std::wstring& orig)
{
    if (orig.empty()) return;
    if (IsWindowUnicode(hCtrl)) {
        UndoSaveW(hCtrl, orig);
        return;
    }
    char buf[514] = { 0 };
    int n = WideCharToMultiByte(932, 0, orig.c_str(), (int)orig.size(),
                                buf, (int)sizeof(buf) - 1,
                                nullptr, nullptr);
    if (n > 0) UndoSaveA(hCtrl, buf, n);
}

// 组合框编辑区原文：Unicode 窗以 W 文本为权威（A 字节是 GBK 反取结果，
// 半角假名会丢成 '?'）；ANSI 窗才参考 A 字节按 932 恢复。
static void DeriveComboOrig(HWND hCtrl, const std::wstring& cur,
                            const char* ab, int al, std::wstring& orig)
{
    if (IsWindowUnicode(hCtrl)) {
        if (DictLookup(cur)) { orig = cur; return; }
        if (const std::wstring* jp = MojibakeLookup(cur)) { orig = *jp; return; }
    }
    if (!ab || al <= 0 || !Decode932Lenient(ab, al, orig))
        orig = cur;
}

