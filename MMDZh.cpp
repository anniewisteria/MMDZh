static std::map<std::wstring, std::wstring> g_dict;
// 我们写入控件的全部中文值（GDI 层遇到这些 GBK 字节时必须按中文渲染）
static std::set<std::wstring> g_zhValues;
// 「GBK 污染形态 W → 日文原文」对照表：对每个词典日文键预演两条损坏链——
// chain1：日文W → SJIS 字节 →(系统码页 GBK 解码)→ 错汉字 W（榐夋拞乧 等）；
// chain2：日文W →(GBK 编码，半角假名无映射变 '?')→ 字节 →(GBK 解码)→
//         问号 W（???????位置角度補正 等，user32 W→A thunk 写 ANSI 窗）。
// 两条链的污染均确定可逆，同表登记。
static std::map<std::wstring, std::wstring> g_mojibakeToJp;
static bool g_dictReady = false;

static void BuildDictionary()
{
    if (g_dictReady) return;
    for (const auto& p : kDict) {
        g_dict[p.jp] = p.zh;
        g_zhValues.insert(p.zh);

        // 预演系统 A→W thunk（CP936）造成的污染，登记反向对照
        int jlen = (int)wcslen(p.jp);
        int cap = WideCharToMultiByte(932, 0, p.jp, jlen,
                                      nullptr, 0, nullptr, nullptr);
        if (cap > 0 && cap < 2048) {
            std::string bytes;
            bytes.resize(cap);
            if (WideCharToMultiByte(932, 0, p.jp, jlen, &bytes[0], cap,
                                    nullptr, nullptr) == cap) {
                bool hi = false;
                for (char ch : bytes)
                    if ((unsigned char)ch >= 0x80) { hi = true; break; }
                if (hi) {
                    int wn = MultiByteToWideChar(936, 0, bytes.data(),
                                                 cap, nullptr, 0);
                    if (wn > 0 && wn < 1024) {
                        std::wstring moji;
                        moji.resize(wn);
                        if (MultiByteToWideChar(936, 0, bytes.data(), cap,
                                                &moji[0], wn) == wn &&
                            moji != p.jp)
                            g_mojibakeToJp.emplace(std::move(moji),
                                                   std::wstring(p.jp));
                    }
                }
            }
        }

        // chain2 预演（第三批 P1/P2/P3）：日文W → GBK 字节，其中无映射
        // 字符（半角假名等）被替换为字面 '?' 0x3F；再按 GBK 解回 W。
        // 日文汉字 GBK 多可编码、原样往返，故产物即「???????+汉字」。
        int cap2 = WideCharToMultiByte(936, 0, p.jp, jlen,
                                       nullptr, 0, nullptr, nullptr);
        if (cap2 > 0 && cap2 < 2048) {
            std::string bytes2;
            bytes2.resize(cap2);
            if (WideCharToMultiByte(936, 0, p.jp, jlen, &bytes2[0], cap2,
                                    nullptr, nullptr) == cap2) {
                bool hasQ = false;
                for (char ch : bytes2)
                    if (ch == '?') { hasQ = true; break; }
                if (hasQ) {
                    int wn2 = MultiByteToWideChar(936, 0, bytes2.data(),
                                                  cap2, nullptr, 0);
                    if (wn2 > 0 && wn2 < 1024) {
                        std::wstring moji2;
                        moji2.resize(wn2);
                        if (MultiByteToWideChar(936, 0, bytes2.data(), cap2,
                                                &moji2[0], wn2) == wn2 &&
                            moji2 != p.jp)
                            g_mojibakeToJp.emplace(std::move(moji2),
                                                   std::wstring(p.jp));
                    }
                }
            }
        }
    }
    g_dictReady = true;
}

static const std::wstring* DictLookup(const std::wstring& s)
{
    auto it = g_dict.find(s);
    return it == g_dict.end() ? nullptr : &it->second;
}

// 坏字 W 是否命中预演对照表；命中即返回确定的日文原文
static const std::wstring* MojibakeLookup(const std::wstring& s)
{
    auto it = g_mojibakeToJp.find(s);
    return it == g_mojibakeToJp.end() ? nullptr : &it->second;
}

