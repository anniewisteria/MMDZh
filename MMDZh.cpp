static int TranslateMenuRecursive(HMENU hMenu)
{
    if (!IsZhOn()) return 0;   // 关闭汉化：弹出菜单保持日文
    int changed = 0;
    int count = GetMenuItemCount(hMenu);
    if (count < 0) return 0;

    for (int i = 0; i < count; ++i) {
        wchar_t buf[512] = { 0 };
        MENUITEMINFOW mii;
        ZeroMemory(&mii, sizeof(mii));
        mii.cbSize      = sizeof(MENUITEMINFOW);
        mii.fMask       = MIIM_FTYPE | MIIM_STRING | MIIM_SUBMENU;
        mii.dwTypeData  = buf;
        mii.cch         = 511;
        if (!GetMenuItemInfoW(hMenu, (UINT)i, TRUE, &mii))
            continue;

        HMENU hSub = mii.hSubMenu;

        if (!(mii.fType & MFT_SEPARATOR) && buf[0] != L'\0') {
            auto* zh = DictLookup(buf);
            if (zh && *zh != buf) {
                // 只留第一次改写前的日文原文，供「关闭汉化」还原
                g_menuOrig.emplace(std::make_pair(hMenu, i), buf);
                MENUITEMINFOW set;
                ZeroMemory(&set, sizeof(set));
                set.cbSize     = sizeof(MENUITEMINFOW);
                set.fMask      = MIIM_STRING;
                set.dwTypeData = const_cast<LPWSTR>(zh->c_str());
                if (SetMenuItemInfoW(hMenu, (UINT)i, TRUE, &set))
                    ++changed;
            }
        }
        if (hSub)
            changed += TranslateMenuRecursive(hSub);
    }
    return changed;
}

// 关闭汉化：按快照把菜单文字改回日文（我们自己的「中文汉化」菜单无快照，
// 天然不受影响）。
static int RestoreMenuRecursive(HMENU hMenu)
{
    int restored = 0;
    int count = GetMenuItemCount(hMenu);
    if (count < 0) return 0;

    for (int i = 0; i < count; ++i) {
        auto it = g_menuOrig.find(std::make_pair(hMenu, i));
        if (it != g_menuOrig.end()) {
            MENUITEMINFOW set;
            ZeroMemory(&set, sizeof(set));
            set.cbSize     = sizeof(MENUITEMINFOW);
            set.fMask      = MIIM_STRING;
            set.dwTypeData = const_cast<LPWSTR>(it->second.c_str());
            if (SetMenuItemInfoW(hMenu, (UINT)i, TRUE, &set))
                ++restored;
        }
        MENUITEMINFOW mii;
        ZeroMemory(&mii, sizeof(mii));
        mii.cbSize = sizeof(MENUITEMINFOW);
        mii.fMask  = MIIM_SUBMENU;
        if (GetMenuItemInfoW(hMenu, (UINT)i, TRUE, &mii) && mii.hSubMenu)
            restored += RestoreMenuRecursive(mii.hSubMenu);
    }
    return restored;
}

static void ApplyMenus(HWND hWnd)
{
    if (!IsZhOn()) return;
    HMENU hMenu = GetMenu(hWnd);
    if (!hMenu) return;
    if (TranslateMenuRecursive(hMenu) > 0)
        DrawMenuBar(hWnd);
}

static void RestoreMenus(HWND hWnd)
{
    HMENU hMenu = GetMenu(hWnd);
    if (!hMenu) return;
    RestoreMenuRecursive(hMenu);
    DrawMenuBar(hWnd);
}

