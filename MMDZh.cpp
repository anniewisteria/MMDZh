{
    caps.clear();
    std::vector<std::wstring> seg;
    for (size_t tpos = 0;;) {
        size_t mark = tmpl.find(L"%s", tpos);
        seg.push_back(tmpl.substr(tpos,
            mark == std::wstring::npos ? std::wstring::npos : mark - tpos));
        if (mark == std::wstring::npos) break;
        tpos = mark + 2;
    }
    size_t pos = 0;
    for (size_t i = 0; i < seg.size(); ++i) {
        size_t hit = std::wstring::npos;
        if (i == 0) {
            if (in.compare(0, seg[0].size(), seg[0]) == 0) hit = 0;
        } else if (i + 1 == seg.size()) {
            // 末段必须精确收尾
            if (in.size() >= seg[i].size()) {
                hit = in.size() - seg[i].size();
                if (hit < pos ||
                    in.compare(hit, seg[i].size(), seg[i]) != 0)
                    hit = std::wstring::npos;
            }
        } else {
            hit = in.find(seg[i], pos);
        }
        if (hit == std::wstring::npos) return false;
        if (i > 0) caps.push_back(in.substr(pos, hit - pos));
        pos = hit + seg[i].size();
    }
    return pos == in.size();
}

// 中文模板里的 %s 数量必须与捕获数一致，逐个替换
static bool BuildZhFromPattern(const DynPattern& p,
                               const std::vector<std::wstring>& caps,
                               std::wstring& out)
{
    out.clear();
    size_t tpos = 0, ci = 0;
    for (;;) {
        size_t mark = std::wstring(p.zh).find(L"%s", tpos);
        std::wstring lit = std::wstring(p.zh).substr(tpos,
            mark == std::wstring::npos ? std::wstring::npos : mark - tpos);
        out += lit;
        if (mark == std::wstring::npos) break;
        if (ci >= caps.size()) return false;
        out += caps[ci++];
        tpos = mark + 2;
    }
    return ci == caps.size();
}

// 直接命中日文模板（GDI 932 路径、932 恢复后的控件文本）
static bool PatternLookupJp(const std::wstring& in, std::wstring& out)
{
    for (const auto& p : kDynPatterns) {
        std::vector<std::wstring> caps;
        std::wstring tmpl(p.jp);
        if (MatchTmpl(in, tmpl, caps))
            return BuildZhFromPattern(p, caps, out);
    }
    return false;
}

